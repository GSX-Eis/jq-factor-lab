def get_previous_trading_day(current_dt, all_trading_days):
    """
    获取当前日期的上一个交易日
    
    [ALIGNMENT] 与云端回测 context.previous_date 对齐
    """
    current_ts = pd.Timestamp(current_dt).normalize()
    
    # 找到当前日期之前的最近交易日
    for i, td in enumerate(all_trading_days):
        td_ts = pd.Timestamp(td).normalize()
        if td_ts >= current_ts and i > 0:
            return pd.Timestamp(all_trading_days[i - 1])
        elif td_ts == current_ts and i > 0:
            return pd.Timestamp(all_trading_days[i - 1])
    
    # Fallback: 如果找不到，简单返回前一天
    return current_ts - timedelta(days=1)


def get_previous_rebalance_date(current_rebalance_dt, all_trading_days):
    """
    获取上一个调仓日（周三）
    
    [PIT FIX] 对于因子计算日期 T-1，应该使用上一个调仓周期的股票池，
    而不是当前调仓日的股票池，以避免 Look-Ahead Bias。
    
    示例：
    - 当前调仓日 = 2025-04-23（周三）
    - 因子计算日期 = 2025-04-22（周二）
    - 上一个调仓日 = 2025-04-16（上周三）
    - 所以 4.22 的因子应该用 4.16 确定的股票池
    
    Args:
        current_rebalance_dt: 当前调仓日（周三）
        all_trading_days: 所有交易日列表
        
    Returns:
        上一个调仓日（周三）
    """
    current_ts = pd.Timestamp(current_rebalance_dt).normalize()
    
    # 向前找上一个周三
    for d in reversed(all_trading_days):
        d_ts = pd.Timestamp(d).normalize()
        # 找到当前日期之前的周三
        if d_ts < current_ts and d_ts.weekday() == 2:  # Wed=2
            return d_ts
    
    # Fallback: 返回7天前
    return current_ts - timedelta(days=7)




def durable_alignment_output(function):
    """Persist producer output even when the notebook browser disconnects."""
    import functools

    @functools.wraps(function)
    def run(*args, **kwargs):
        fingerprint = ALIGNMENT_FINGERPRINT
        if not fingerprint:
            return function(*args, **kwargs)
        import re
        if not re.fullmatch('[0-9a-f]{64}', fingerprint):
            raise ValueError('invalid alignment fingerprint for durable output')
        import contextlib
        import sys
        import traceback

        class Tee:
            def __init__(self, original, journal):
                self.original = original
                self.journal = journal

            def write(self, text):
                self.journal.write(text)
                self.journal.flush()
                return self.original.write(text)

            def flush(self):
                self.journal.flush()
                self.original.flush()

            def isatty(self):
                return False

        path = 'alignment_cloud_' + fingerprint + '.log'
        with open(path, 'w', encoding='utf-8') as journal:
            with contextlib.redirect_stdout(Tee(sys.stdout, journal)), contextlib.redirect_stderr(Tee(sys.stderr, journal)):
                print('ALIGNMENT_PRODUCER_STARTED|' + fingerprint)
                try:
                    result = function(*args, **kwargs)
                except BaseException:
                    traceback.print_exc()
                    raise
                print('ALIGNMENT_PRODUCER_DONE|' + fingerprint)
                return result

    return run


