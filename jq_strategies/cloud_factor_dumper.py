def filter_st_stock(stock_list, current_dt):
    # get_extras('is_st', ...) is the research way
    is_st = get_extras('is_st', stock_list, end_date=current_dt, count=1)
    if is_st.empty:
        return stock_list
    # is_st is a dataframe usually (date x stocks), boolean
    # Get the last row (target date)
    st_status = is_st.iloc[-1]
    # Keep false
    norm_stocks = st_status[st_status == False].index.tolist()
    # Intersect with stock_list to maintain order/subset
    return [s for s in stock_list if s in norm_stocks]

def filter_kcbj_stock(stock_list):
    # Static filter
    return [s for s in stock_list if not (s.startswith('68') or s.startswith('8') or s.startswith('4') or s.startswith('30'))]

