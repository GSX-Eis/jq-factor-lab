def select_factor_row_for_date(factor_name, result, target_date):
    if isinstance(result, pd.Series):
        if result.empty:
            raise ValueError("empty_factor_series")
        return result, pd.to_datetime(target_date).normalize()
    if not isinstance(result, pd.DataFrame):
        raise TypeError(f"{factor_name}: unsupported_result_type")
    if result.empty:
        raise ValueError("empty_factor_dataframe")
    if not isinstance(result.index, pd.DatetimeIndex):
        raise ValueError("unexpected_non_datetime_index")

    normalized_target = pd.to_datetime(target_date).normalize()
    filtered = result.loc[result.index <= normalized_target]
    if filtered.empty:
        raise ValueError("no_observation_on_or_before_target_date")
    last_date = filtered.index.max()
    row = filtered.loc[last_date]
    if isinstance(row, pd.DataFrame):
        row = row.iloc[-1]
    if not isinstance(row, pd.Series) or row.empty:
        raise ValueError("empty_factor_row")
    return row, last_date









