def streaming_csv_fingerprint(frame):
    """Hash the exact default CSV byte stream with bounded output buffering."""
    import hashlib
    import io
    digest = hashlib.sha256()

    class DigestSink(io.RawIOBase):
        def writable(self):
            return True

        def write(self, data):
            digest.update(data)
            return len(data)

    with io.TextIOWrapper(io.BufferedWriter(DigestSink(), buffer_size=65536),
                          encoding='utf-8', newline='') as output:
        frame.to_csv(output, index=False)
        output.flush()
    return digest.hexdigest()


